DRAWABLE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Phosphor Icons (MIT). Generated by tools/phosphor.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="256"
    android:viewportHeight="256">
{paths}
</vector>
"""

PATH = """    <path
        android:pathData="{d}"
        android:fillColor="#FF000000" />
"""


def fetch(style: str, name: str) -> str:
    url = f"{BASE}/{style}/{name}.svg"
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def convert(svg: str) -> list[str]:
    # Phosphor icons are one or more filled <path> elements at a 256 viewport.
    return [
        d.strip()
        for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
        if d.strip()
    ]


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    out = root / "app/src/main/res/drawable"
    out.mkdir(parents=True, exist_ok=True)

    written = 0
    for app_name, (style, phosphor_name) in ICONS.items():
        try:
            svg = fetch(style, phosphor_name)
        except Exception as error:  # noqa: BLE001 - report and keep going
            print(f"  FAILED {app_name} ({phosphor_name}): {error}")
            continue

        paths = convert(svg)
        if not paths:
            print(f"  FAILED {app_name}: no paths found")
            continue

        file_name = "ic_ph_" + re.sub(r"(?<!^)(?=[A-Z])", "_", app_name).lower() + ".xml"
        body = "".join(PATH.format(d=d) for d in paths)
        (out / file_name).write_text(DRAWABLE.format(paths=body), encoding="utf-8")
        written += 1

    print(f"{written} icons written to {out}")
    return 0 if written == len(ICONS) else 1


if __name__ == "__main__":
    sys.exit(main())
