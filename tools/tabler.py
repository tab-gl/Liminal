HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Tabler Icons {version} — @tabler/icons (MIT). Generated by tools/tabler.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
"""
PATH = """    <path
        android:pathData="{d}"
        android:fillColor="{fill}"
        android:strokeColor="#FF000000"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
"""
FOOTER = "</vector>\n"


def circle_to_path(cx, cy, r):
    """A circle as two arcs, which is what Android vectors accept."""
    return (
        f"M {cx - r} {cy} "
        f"a {r} {r} 0 1 0 {2 * r} 0 "
        f"a {r} {r} 0 1 0 {-2 * r} 0"
    )


def rect_to_path(x, y, w, h, rx):
    if rx <= 0:
        return f"M {x} {y} H {x + w} V {y + h} H {x} Z"
    return (
        f"M {x + rx} {y} H {x + w - rx} A {rx} {rx} 0 0 1 {x + w} {y + rx} "
        f"V {y + h - rx} A {rx} {rx} 0 0 1 {x + w - rx} {y + h} "
        f"H {x + rx} A {rx} {rx} 0 0 1 {x} {y + h - rx} "
        f"V {y + rx} A {rx} {rx} 0 0 1 {x + rx} {y} Z"
    )


def element_to_path(tag, attrs):
    """Turns one SVG element into (pathData, is_filled).

    Outline icons are mostly strokes, but not entirely: the pips on a dice or the
    dot on an 'i' are solid circles. Skipping those turned the dice into an empty
    square, so a solid element is now emitted as a filled path instead of being
    dropped.
    """
    filled = attrs.get("fill", "none") not in ("none", "", "transparent")
    if tag == "path":
        d = attrs.get("d")
    elif tag == "circle":
        d = circle_to_path(float(attrs["cx"]), float(attrs["cy"]), float(attrs["r"]))
    elif tag == "line":
        d = f"M {attrs['x1']} {attrs['y1']} L {attrs['x2']} {attrs['y2']}"
    elif tag == "polyline":
        points = attrs["points"].split()
        d = "M " + " L ".join(points)
    elif tag == "polygon":
        points = attrs["points"].split()
        d = "M " + " L ".join(points) + " Z"
    elif tag == "rect":
        d = rect_to_path(
            float(attrs.get("x", 0)),
            float(attrs.get("y", 0)),
            float(attrs["width"]),
            float(attrs["height"]),
            float(attrs.get("rx", 0) or 0),
        )
    else:
        d = None
    return (d, filled) if d else None


def convert(svg: str) -> str:
    body = []
    for match in re.finditer(r"<(\w+)\s([^>]*?)/?>", svg):
        tag, raw = match.group(1), match.group(2)
        if tag in ("svg", "g", "defs", "title"):
            continue
        attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', raw))
        converted = element_to_path(tag, attrs)
        # Tabler SVGs carry a 24x24 no-op box; stroked, it would draw a border.
        if converted and converted[0].replace(" ", "").lower() not in ("m00h24v24h0z",):
            d, filled = converted
            body.append(
                FILLED_PATH.format(d=d.strip())
                if filled
                else PATH.format(d=d.strip(), fill="@android:color/transparent")
            )
    if not body:
        raise ValueError("no drawable elements found")
    return HEADER.format(version=VERSION) + "".join(body) + FOOTER


FILLED_PATH = """    <path
        android:pathData="{d}"
        android:fillColor="#FF000000"
        android:strokeWidth="0" />
"""


def convert_filled(svg: str) -> str:
    """Filled icons paint their shapes instead of stroking them."""
    body = []
    for match in re.finditer(r"<(path|circle|rect)\s([^>]*?)/?>", svg):
        tag, raw = match.group(1), match.group(2)
        attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', raw))
        # Tabler's filled SVGs carry a transparent 24x24 box first
        if attrs.get("fill") == "none":
            continue
        if tag == "path":
            d = attrs.get("d")
        elif tag == "circle":
            d = circle_to_path(float(attrs["cx"]), float(attrs["cy"]), float(attrs["r"]))
        elif tag == "rect":
            d = rect_to_path(
                float(attrs.get("x", 0)), float(attrs.get("y", 0)),
                float(attrs["width"]), float(attrs["height"]),
                float(attrs.get("rx", 0) or 0),
            )
        else:
            d = None
        if d and d.replace(" ", "").lower() != "m00h24v24h0z":
            body.append(FILLED_PATH.format(d=d.strip()))
    if not body:
        raise ValueError("no filled shapes found")
    return HEADER.format(version=VERSION) + "".join(body) + FOOTER


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    written, failed = [], []
    for name, tabler in ICONS.items():
        url = f"{CDN}/{tabler}.svg"
        try:
            with urllib.request.urlopen(url, timeout=30) as response:
                svg = response.read().decode()
            (OUT / f"ic_tb_{name.lower()}.xml").write_text(convert(svg))
            written.append(name)
        except Exception as error:  # noqa: BLE001 - report and continue
            failed.append(f"{name} ({tabler}): {error}")

    for name, tabler in FILLED.items():
        url = f"{FILLED_CDN}/{tabler}.svg"
        try:
            with urllib.request.urlopen(url, timeout=30) as response:
                svg = response.read().decode()
            (OUT / f"ic_tb_{name.lower()}_filled.xml").write_text(convert_filled(svg))
            written.append(f"{name} (filled)")
        except Exception as error:  # noqa: BLE001
            failed.append(f"{name} filled ({tabler}): {error}")

    print(f"{len(written)} icons written to {OUT}")
    for item in failed:
        print(f"  FAILED {item}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
