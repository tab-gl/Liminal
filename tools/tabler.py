#!/usr/bin/env python3
"""Fetches Tabler icons and compiles them into Android vector drawables.

Tabler ships SVG only, and its outline set draws with strokes rather than fills,
so each element is emitted as a stroked path at the same 24dp viewport and a
2px stroke — which is Tabler's own default and keeps the set optically
consistent.

    python3 tools/tabler.py

Writes app/src/main/res/drawable/ic_tb_*.xml and prints the Compose mapping.
"""
